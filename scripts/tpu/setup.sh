#!/usr/bin/env bash
# One-command setup of a fresh ECE661 TPU session (v6e-1). Safe to re-run.
#
#   git clone <your repo url> ~/deepfake-detection      # first, on the TPU machine
#   bash ~/deepfake-detection/scripts/tpu/setup.sh
#   source ~/dff_env.sh                                 # in every new shell afterwards
#
# What it does (the machine's disk is wiped when the session ends, so most steps repeat
# every session; anything slow is cached in the group bucket):
#   1. checks the group bucket (/mnt/group) and Python (3.10-3.13 for torch_xla 2.9)
#   2. creates a virtualenv on local disk and installs requirements-tpu.txt
#      (pip's download cache lives in the bucket, so later sessions install faster)
#   3. puts the dataset on LOCAL disk: zips are cached in /mnt/group/dff_zips (downloaded
#      from Hugging Face only the first time), then extracted to ~/dff
#   4. writes configs/local.yaml and ~/dff_env.sh (venv + DFF_ROOT, DFF_OUTPUT_ROOT, PJRT_DEVICE)
#   5. checks the local data against the committed manifests and that the TPU is visible
#
# Overridable with environment variables: GROUP_DIR, LOCAL_DATA, VENV, PYTHON, DFF_USER.
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
GROUP_DIR="${GROUP_DIR:-/mnt/group}"
LOCAL_DATA="${LOCAL_DATA:-$HOME/dff}"
VENV="${VENV:-$HOME/venv-dff}"
PYTHON="${PYTHON:-python3}"
ZIP_CACHE="$GROUP_DIR/dff_zips"
OUTPUT_ROOT="$GROUP_DIR/outputs"
ENV_FILE="$HOME/dff_env.sh"

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die()  { printf '\033[31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

cd "$PROJECT_DIR"

# --------------------------------------------------------------------------- 1. checks
step "1/5 Checking group bucket and Python"
[ -d "$GROUP_DIR" ] || die "$GROUP_DIR not found. Checkpoints must go to the group bucket (machine disk is deleted)."
touch "$GROUP_DIR/.dff_write_test" 2>/dev/null && rm -f "$GROUP_DIR/.dff_write_test" \
  || die "$GROUP_DIR is not writable."
mkdir -p "$ZIP_CACHE" "$OUTPUT_ROOT" "$GROUP_DIR/cache/pip"
command -v "$PYTHON" >/dev/null || die "$PYTHON not found."
PYV="$("$PYTHON" -c 'import sys; print(f"{sys.version_info[0]}.{sys.version_info[1]}")')"
case "$PYV" in
  3.10|3.11|3.12|3.13) echo "Python $PYV OK" ;;
  *) die "Python $PYV: torch_xla 2.9 needs 3.10-3.13. Set PYTHON=python3.12 (or similar)." ;;
esac
df -h "$HOME" | tail -1 | awk '{print "Local disk free: " $4 " (dataset needs ~5 GB)"}'

# --------------------------------------------------------------------------- 2. venv
step "2/5 Python environment ($VENV)"
if [ ! -x "$VENV/bin/python" ]; then
  if ! "$PYTHON" -m venv "$VENV" 2>/dev/null; then
    echo "python venv module missing; installing python${PYV}-venv (needs sudo)"
    sudo apt-get update -qq && sudo apt-get install -y -qq "python${PYV}-venv" \
      || die "Could not install python${PYV}-venv."
    "$PYTHON" -m venv "$VENV"
  fi
fi
# shellcheck disable=SC1091
source "$VENV/bin/activate"
REQ_HASH="$(cat requirements-tpu.txt requirements-base.txt | sha256sum | cut -c1-16)"
if [ "$(cat "$VENV/.req_hash" 2>/dev/null || true)" != "$REQ_HASH" ]; then
  export PIP_CACHE_DIR="$GROUP_DIR/cache/pip"
  python -m pip install -q --upgrade pip
  python -m pip install -q -r requirements-tpu.txt
  echo "$REQ_HASH" > "$VENV/.req_hash"
else
  echo "Requirements already installed."
fi
python -c "import torch, torchvision, torch_xla; print('torch', torch.__version__, '| torchvision', torchvision.__version__, '| torch_xla', torch_xla.__version__)"

# --------------------------------------------------------------------------- 3. dataset
step "3/5 Dataset -> $LOCAL_DATA (zip cache: $ZIP_CACHE)"
python -m src.data.download --dest "$LOCAL_DATA" --zip-cache "$ZIP_CACHE"

# --------------------------------------------------------------------------- 4. config
step "4/5 Writing configs/local.yaml and $ENV_FILE"
printf 'dataset_root: %s\n' "$LOCAL_DATA" > configs/local.yaml
cat > "$ENV_FILE" <<EOF
# Generated by scripts/tpu/setup.sh — run "source ~/dff_env.sh" in every new shell.
source "$VENV/bin/activate"
export PJRT_DEVICE=TPU                      # torch_xla runtime: use the TPU
export DFF_ROOT="$LOCAL_DATA"               # dataset on local disk (fast)
export DFF_OUTPUT_ROOT="$OUTPUT_ROOT"       # runs + checkpoints in the bucket (survive the session)
export DFF_USER="${DFF_USER:-${USER:-tpu}}"
cd "$PROJECT_DIR"
EOF
# shellcheck disable=SC1090
source "$ENV_FILE"
echo "Wrote $ENV_FILE"

# --------------------------------------------------------------------------- 5. checks
step "5/5 Verifying data and TPU"
python -m src.data.verify --dataset-root "$LOCAL_DATA"
if python -c "from src.device import resolve_device; print(resolve_device('tpu').describe())"; then
  echo "TPU detected."
else
  echo -e "\033[33mWARNING: TPU not detected. Training with --device tpu will fail; send the error above.\033[0m"
fi

step "Setup complete"
cat <<EOF
Next steps:
  source ~/dff_env.sh
  tmux new -s train                       # keeps training alive if your SSH connection drops
  bash scripts/tpu/run_phase2.sh --smoke  # ~minutes: checks the whole TPU path, prints epoch times
  bash scripts/tpu/run_phase2.sh          # all 6 Phase 2 configurations x 3 seeds (resumable)
Results: $OUTPUT_ROOT   (copy small files into the repo with scripts/tpu/collect_results.sh)
EOF
